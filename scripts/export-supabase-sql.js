const fs = require("fs");
const path = require("path");
const sqlite3 = require("sqlite3").verbose();

const dbPath = path.join(process.cwd(), "data", "database.db");
const outputPath = path.join(process.cwd(), "scripts", "supabase-import.sql");

function escapeSqlString(value) {
  return value.replace(/'/g, "''");
}

function toSqlValue(value) {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") return String(value);
  return `'${escapeSqlString(String(value))}'`;
}

function allAsync(db, sql) {
  return new Promise((resolve, reject) => {
    db.all(sql, (err, rows) => {
      if (err) return reject(err);
      return resolve(rows);
    });
  });
}

function insertStatement(table, columns, rows) {
  if (!rows.length) return `-- No rows in ${table}\n`;

  const values = rows
    .map((row) => {
      const tuple = columns.map((col) => toSqlValue(row[col])).join(", ");
      return `(${tuple})`;
    })
    .join(",\n");

  return `INSERT INTO public.${table} (${columns.join(", ")}) VALUES\n${values};\n`;
}

async function main() {
  const db = new sqlite3.Database(dbPath);

  try {
    const products = await allAsync(db, "SELECT * FROM products ORDER BY id ASC");
    const users = await allAsync(db, "SELECT * FROM users ORDER BY id ASC");

    const sqlParts = [
      "-- Generated from SQLite for Supabase Postgres",
      "BEGIN;",
      "",
      "CREATE TABLE IF NOT EXISTS public.products (",
      "  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,",
      "  name TEXT NOT NULL,",
      "  price TEXT NOT NULL,",
      "  description TEXT,",
      "  icon TEXT,",
      "  color TEXT,",
      "  tag TEXT",
      ");",
      "",
      "CREATE TABLE IF NOT EXISTS public.users (",
      "  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,",
      "  email TEXT UNIQUE,",
      "  name TEXT,",
      "  username TEXT UNIQUE,",
      "  phone TEXT UNIQUE,",
      "  address TEXT,",
      "  gender TEXT,",
      "  password_hash TEXT NOT NULL,",
      "  role TEXT DEFAULT 'user',",
      "  profile_complete INTEGER DEFAULT 0,",
      "  seen_profile_prompt INTEGER DEFAULT 0,",
      "  created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW()",
      ");",
      "",
      "TRUNCATE TABLE public.products RESTART IDENTITY CASCADE;",
      "TRUNCATE TABLE public.users RESTART IDENTITY CASCADE;",
      "",
      insertStatement(
        "products",
        ["id", "name", "price", "description", "icon", "color", "tag"],
        products
      ),
      insertStatement(
        "users",
        [
          "id",
          "email",
          "name",
          "username",
          "phone",
          "address",
          "gender",
          "password_hash",
          "role",
          "profile_complete",
          "seen_profile_prompt",
          "created_at",
        ],
        users
      ),
      "SELECT setval(pg_get_serial_sequence('public.products', 'id'), COALESCE((SELECT MAX(id) FROM public.products), 1), true);",
      "SELECT setval(pg_get_serial_sequence('public.users', 'id'), COALESCE((SELECT MAX(id) FROM public.users), 1), true);",
      "",
      "COMMIT;",
      "",
    ];

    fs.writeFileSync(outputPath, sqlParts.join("\n"), "utf8");
    console.log(`Exported Supabase SQL to: ${outputPath}`);
    console.log(`products: ${products.length} row(s), users: ${users.length} row(s)`);
  } finally {
    db.close();
  }
}

main().catch((err) => {
  console.error("Export failed:", err);
  process.exit(1);
});
